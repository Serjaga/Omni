use std::{env, fs, path::{Path, PathBuf}};

fn watch_tree(path: &Path) {
    println!("cargo:rerun-if-changed={}", path.display());
    if let Ok(entries) = fs::read_dir(path) {
        for entry in entries.flatten() {
            let p=entry.path();
            if p.is_dir() { watch_tree(&p); } else { println!("cargo:rerun-if-changed={}", p.display()); }
        }
    }
}
fn module_entry(dir: &Path) -> String {
    let text=fs::read_to_string(dir.join("module.toml")).unwrap_or_default();
    for line in text.lines() {
        let line=line.trim();
        if let Some((key,value))=line.split_once('=') {
            if key.trim()=="entry" {
                let raw=value.trim();
                if let Some(rest)=raw.strip_prefix('"') { if let Some(end)=rest.find('"') { return rest[..end].to_string(); } }
                return raw.to_string();
            }
        }
    }
    "src/module.rs".to_string()
}

fn valid_id(s: &str) -> bool {
    !s.is_empty() && s.len() <= 64 && s.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-')
}
fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let installed = manifest.join("../modules/installed");
    println!("cargo:rerun-if-changed={}", installed.display());
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("generated_modules.rs");
    let mut ids = Vec::new();
    if let Ok(entries) = fs::read_dir(&installed) {
        for entry in entries.flatten() {
            let path = entry.path();
            if !path.is_dir() { continue; }
            let Some(id) = path.file_name().and_then(|x| x.to_str()) else { continue; };
            if !valid_id(id) { continue; }
            watch_tree(&path);
            let entry=module_entry(&path);
            if !entry.starts_with("src/") || entry.contains("..") || !path.join(&entry).is_file() { continue; }
            ids.push(id.to_string());
        }
    }
    ids.sort();
    let mut code = String::from("// Generated by server/build.rs. Do not edit.\n");
    let rust_names: Vec<String> = ids.iter().map(|id| format!("m_{}", id.as_bytes().iter().map(|b| format!("{b:02x}")).collect::<String>())).collect();
    for (id, rust_name) in ids.iter().zip(rust_names.iter()) {
        let module_dir=installed.join(id);
        let src = module_dir.join(module_entry(&module_dir));
        let path = src.to_string_lossy().replace('\\', "\\\\").replace('"', "\\\"");
        code.push_str(&format!("#[path = \"{path}\"] pub mod {rust_name};\n"));
    }
    code.push_str("pub async fn start(state: crate::SharedState) {\n");
    for rust_name in &rust_names { code.push_str(&format!("    {rust_name}::start(state.clone()).await;\n")); }
    code.push_str("}\n");
    code.push_str("pub async fn dispatch(ctx: crate::api::ApiCtx) -> Option<axum::response::Response<axum::body::Body>> {\n");
    for rust_name in &rust_names { code.push_str(&format!("    if let Some(response) = {rust_name}::dispatch(ctx.clone()).await {{ return Some(response); }}\n")); }
    code.push_str("    None\n}\n");
    fs::write(out, code).expect("write generated module registry");
}
